def test_F_restart_before_ready_no_duplicate() -> None:
    """Simulates two separate cycles (two independent reloads of durable
    state) while still not retry-ready — must agree both times and never
    grow proposal lineage just from being asked twice."""
    p = _make_low_risk_proposal("synthetic F: restart before ready")
    job_id = _make_failed_job(error_class="infra", terminal_result="timeout")
    proposal_mod.append_implementation_job(p.proposal_id, job_id)
    p1 = proposal_mod.load(p.proposal_id)
    job1, note1, refuse1 = advance._resolve_prior_attempt(p1, requested_by="test")
    p2 = proposal_mod.load(p.proposal_id)  # simulates a fresh process reloading durable state
    job2, note2, refuse2 = advance._resolve_prior_attempt(p2, requested_by="test")
    check("F: both independent reloads refuse identically (not yet ready)",
          refuse1 is True and refuse2 is True, (refuse1, refuse2))
    p_final = proposal_mod.load(p.proposal_id)
    check("F: implementation_job_ids unchanged across both calls",
          p_final.implementation_job_ids == [job_id], p_final.implementation_job_ids)
    _cleanup(p.proposal_id, "test F cleanup")


def test_G_restart_after_ready_allows_one_continuation() -> None:
    p = _make_low_risk_proposal("synthetic G: restart after ready")
    job_id = _make_failed_job(error_class="infra", terminal_result="timeout")
    _backdate_updated_at(job_id, 200)
    proposal_mod.append_implementation_job(p.proposal_id, job_id)
    p_reloaded = proposal_mod.load(p.proposal_id)  # simulates a fresh process/restart reading durable state
    job, note, refuse = advance._resolve_prior_attempt(p_reloaded, requested_by="test")
    check("G: refuse=False after a simulated restart, once genuinely ready", refuse is False, note)
    _cleanup(p.proposal_id, "test G cleanup")


def test_H_repeated_calls_never_grow_lineage_on_their_own() -> None:
    """No infinite-retry surface: repeatedly asking (as repeated
    advance_eligible() cycles would) while not-yet-ready must never itself
    create a job or mutate proposal lineage -- _resolve_prior_attempt()
    never calls submit_job(); only advance_one()'s own router does that,
    gated by the unchanged, separate MAX_IMPLEMENTATION_ATTEMPTS ceiling."""
    p = _make_low_risk_proposal("synthetic H: repeated calls bounded")
    job_id = _make_failed_job(error_class="infra", terminal_result="timeout")
    proposal_mod.append_implementation_job(p.proposal_id, job_id)
    for i in range(5):
        p_i = proposal_mod.load(p.proposal_id)
        job, note, refuse = advance._resolve_prior_attempt(p_i, requested_by="test")
        check(f"H: repeated call #{i + 1} still refuses cleanly, no exception", refuse is True, note)
    p_final = proposal_mod.load(p.proposal_id)
    check("H: implementation_job_ids never grew across 5 repeated calls",
          p_final.implementation_job_ids == [job_id], p_final.implementation_job_ids)
    _cleanup(p.proposal_id, "test H cleanup")


def test_I_fine_grained_subhourly_checks_track_real_elapsed_time() -> None:
    """No hourly-watchdog dependency: readiness is checked at several
    points seconds apart (all far under an hour) and tracks real elapsed
    time purely from persisted state, exactly as job_ledger.is_retry_ready
    itself already proves in isolation (test_job_ledger_no_watchdog_
    dependency.py) -- this proves the SAME property holds through the
    real _resolve_prior_attempt() call path, not just the bare helper."""
    p = _make_low_risk_proposal("synthetic I: sub-hourly checks")
    job_id = _make_failed_job(error_class="infra", terminal_result="timeout")
    proposal_mod.append_implementation_job(p.proposal_id, job_id)
    # attempt=1 -> backoff is exactly 60s (60 + (1-1)%61); values kept well
    # clear of that boundary to avoid execution-time flakiness.
    for seconds_ago, expect_ready in [(200, True), (70, True), (30, False)]:
        _backdate_updated_at(job_id, seconds_ago)
        p_i = proposal_mod.load(p.proposal_id)
        job, note, refuse = advance._resolve_prior_attempt(p_i, requested_by="test")
        check(f"I: seconds_ago={seconds_ago} -> refuse={not expect_ready} as expected",
              refuse == (not expect_ready), note)
    _cleanup(p.proposal_id, "test I cleanup")


