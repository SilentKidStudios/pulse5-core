from __future__ import annotations

import sys
import uuid
from datetime import datetime, timedelta, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import job_ledger
from evolution import advance
from evolution import proposal as proposal_mod

FAILURES: list[str] = []


def check(name: str, condition: bool, detail: str = "") -> None:
    status = "PASS" if condition else "FAIL"
    print(f"[{status}] {name}" + (f" — {detail}" if detail and not condition else ""))
    if not condition:
        FAILURES.append(name)


def _make_low_risk_proposal(weakness: str) -> proposal_mod.Proposal:
    return proposal_mod.create(observed_weakness=weakness, proposed_upgrade="n/a", risk_score="low", origin="manual")


def _cleanup(proposal_id: str, note: str) -> None:
    p = proposal_mod.load(proposal_id)
    if p.status not in proposal_mod.CLOSED_STATUSES:
        proposal_mod.advance(proposal_id, proposal_mod.ProposalStatus.REJECTED, note=note)
        proposal_mod.record_lesson(proposal_id, note)


def _make_failed_job(*, error_class: str, terminal_result: str, risk_class: str = "low",
                      approval_state: str = "not_required", authority_state: str = "granted") -> str:
    """A real, durable, terminal FAILED job_ledger record -- same shape
    bridge.py/omniengineer_harness.py produce (AUTHORIZED checkpoint first,
    matching every real call site, then the terminal FAILED checkpoint)."""
    job_id = str(uuid.uuid4())
    job_ledger.create(job_id, task=f"synthetic short-cadence test {job_id}", requested_by="test", sandbox_path="/tmp")
    job_ledger.checkpoint(job_id, job_ledger.JobState.AUTHORIZED, risk_class=risk_class,
                           approval_state=approval_state, authority_state=authority_state)
    job_ledger.checkpoint(job_id, job_ledger.JobState.FAILED, terminal_result=terminal_result, error_class=error_class)
    return job_id


def _backdate_updated_at(job_id: str, seconds_ago: int) -> None:
    """Same established pattern as tests/test_bridge_ledger.py's
    _backdate_heartbeat() -- direct load + mutate + the module's own
    _atomic_write_json(), never hand-editing ledger.json as raw text."""
    r = job_ledger.load(job_id)
    r.updated_at = (datetime.now(timezone.utc) - timedelta(seconds=seconds_ago)).isoformat()
    job_ledger._atomic_write_json(job_ledger._path(job_id), job_ledger.asdict(r))


def test_A_transient_not_ready_waits_no_dispatch() -> None:
    p = _make_low_risk_proposal("synthetic A: transient not ready")
    job_id = _make_failed_job(error_class="infra", terminal_result="timeout")
    proposal_mod.append_implementation_job(p.proposal_id, job_id)
    p = proposal_mod.load(p.proposal_id)
    job, note, refuse = advance._resolve_prior_attempt(p, requested_by="test")
    check("A: refuse=True — waiting, not yet retry-ready (just failed, backoff is 60-120s)", refuse is True, note)
    check("A: no job returned — no dispatch", job is None)
    p_after = proposal_mod.load(p.proposal_id)
    check("A: attempt ordinal (implementation_job_ids) unchanged by the wait itself",
          p_after.implementation_job_ids == [job_id], p_after.implementation_job_ids)
    _cleanup(p.proposal_id, "test A cleanup")


def test_B_transient_ready_allows_exactly_one_continuation() -> None:
    p = _make_low_risk_proposal("synthetic B: transient ready")
    job_id = _make_failed_job(error_class="infra", terminal_result="model_unavailable")
    _backdate_updated_at(job_id, 200)  # well past the 60-120s bound
    proposal_mod.append_implementation_job(p.proposal_id, job_id)
    p = proposal_mod.load(p.proposal_id)
    job, note, refuse = advance._resolve_prior_attempt(p, requested_by="test")
    check("B: refuse=False — retry-ready, proceeds to the existing attempt-budget/router path", refuse is False, note)
    check("B: job is None — a genuinely fresh attempt, not a reused one", job is None)
    _cleanup(p.proposal_id, "test B cleanup")


def test_C_non_transient_excluded_from_new_path() -> None:
    p = _make_low_risk_proposal("synthetic C: non-transient excluded")
    job_id = _make_failed_job(error_class="validation", terminal_result="succeeded_validation_failed")
    proposal_mod.append_implementation_job(p.proposal_id, job_id)
